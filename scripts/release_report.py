"""Write docs/report.md for a release from its single data source.

    python scripts/release_report.py

Every number comes from docs/leaderboard.json (validated rows, grouped by compatibility
key), data/labels/adjudication.json and the release spec in configs/. Rows are compared
only within a group. The report generated by the older pipeline for 0.2.4 and earlier
stays in git history; scripts/results_doc.py now writes historical tables only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import momentbench  # noqa: E402


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}"


def ci(c) -> str:
    return "" if not c else f" ({100 * c[0]:.0f} to {100 * c[1]:.0f})"


def name(r: dict) -> str:
    return r["model_id"] + (" (API)" if r["model_id"].startswith("claude")
                            and r["harness"] == "api" else "")


def group_table(g: dict) -> str:
    lines = ["| Model | Harness | Positive R@1 (95% CI, queries) | R@1, all (95% CI) | "
             "No-answer | Net | $/query |", "|---|---|---|---|---|---|---|"]
    for r in g["rows"]:
        cost = r.get("mean_cost_usd_per_query")
        lines.append(
            f"| {name(r)} | {r['harness']} | {pct(r['positive_recall_at_1'])}"
            f"{ci(r.get('positive_recall_at_1_ci95'))} | {pct(r['recall_at_1'])}"
            f"{ci(r['recall_at_1_ci95'])} | {pct(r.get('no_answer_accuracy'))} | "
            f"{'' if r.get('net_score') is None else format(r['net_score'], '+.2f')} | "
            f"{'n/a' if cost is None else f'${cost:.3f}'}"
            f"{'*' if r['harness'] == 'claude-code' and cost is not None else ''} |")
    for x in g.get("not_run", []):
        label = name({"model_id": x["model_id"], "harness": x["harness"]})
        lines.append(f"| {label} | {x['harness']} | not run: {x.get('reason', '')} | | | | |")
    return "\n".join(lines)


def main() -> None:
    v = momentbench.__version__
    board = json.loads((ROOT / "docs/leaderboard.json").read_text())
    labels = json.loads((ROOT / "data/labels/adjudication.json").read_text())["summary"]
    absence = labels.get("absence", {})
    control = (absence.get("controls") or [{}])[0]
    primary = board["primary_keys"]
    assets = json.loads((ROOT / "data/corpus_manifests/sample_manifest.json").read_text())
    minutes = round(sum(a["duration_s"] for a in assets) / 60)
    published = sum(len(json.loads((ROOT / f"data/queries/{d}_v0.2.json").read_text()))
                    for d in ("film", "aerospace", "robotics"))
    held = json.loads((ROOT / "data/heldout_commitments.json").read_text())["count"]
    sections = []
    for domain in ("film", "aerospace", "robotics"):
        groups = [g for g in board["groups"] if g["domain"] == domain]
        main_g = next((g for g in groups if g["compatibility_key"] == primary.get(domain)),
                      None) or next((g for g in groups if g["condition"] ==
                                     "anonymized titles, standard prompt"), None)
        if main_g is None:
            continue
        n = main_g["rows"][0]["num_queries"] if main_g["rows"] else "n/a"
        part = [f"### {domain.title()} ({main_g['queries_file']}, {n} queries)", "",
                f"Primary group: {main_g['condition']}, compatibility key "
                f"`{main_g['compatibility_key']}`.", "", group_table(main_g)]
        for g in groups:
            if g is main_g or not (g["rows"] or g.get("not_run")):
                continue
            key = f"key `{g['compatibility_key']}`" if g["compatibility_key"] else "no runs yet"
            part += ["", f"Other condition: {g['condition']} ({key}), ranked only within "
                     "itself:", "", group_table(g)]
        sections.append("\n".join(part))
    report = f"""# MomentBench {v}: technical report

*Generated by `scripts/release_report.py` from `docs/leaderboard.json`,
`data/labels/adjudication.json` and `configs/release_{v}.json`. Do not edit by hand.*

## Task

Given a text request and a corpus of {len(assets)} videos ({minutes} minutes of Blender open
movies and NASA aerospace and robotics footage, public domain or CC BY), return the
right video and the right few seconds, or an empty answer when nothing in the corpus
matches. A model searches with tools (list videos, search and read transcripts, sample
frames as JPEGs) under a fixed budget; a retrieval system can submit ranked moments
directly (the prediction-file track). `docs/protocol.md` and `docs/input-spec.md`
define the task exactly.

## Labels

Claude drafted, verified and reviewed the queries. Two other model families then
judged every published query against its current annotation (`docs/labels.md`).
Of {published + held} queries, {published} are published, {held} are held out (committed
by hash in `data/heldout_commitments.json`). Of
{labels.get('queries')} published queries, {labels.get('scored')} are scored (both
judges accepted) and {labels.get('provisional')} provisional. Results below use the
scored set. Model disagreement is not an annotation-error estimate, and selecting the
scored set changes coverage (multi-shot queries are scored less often). No-answer
queries were screened against the whole corpus; in a control the screen found
{control.get('found')} of {control.get('true_descriptions')} true descriptions, so
no-answer accuracy and net score are **exploratory**. There is no human review yet.

## Results

Recall@1 counts a hit when the first answer is in the right video with temporal IoU of
at least 0.5. **Positive R@1** is Recall@1 on queries that have a gold moment, the
headline localization number; its interval is a query bootstrap (query sampling), and
run-to-run variation is separate (one trial per query in this release). Net score is
+1 per correct answer, -1 per wrong moment and 0 per abstention. Rows are compared
only within a group: a group is one compatibility key, so its rows ran the same
queries, corpus, transcripts, prompt, tools, budget and conditions. Record runs use
anonymized titles. `*` Claude Code runs are on a subscription; their cost is what the
tokens would cost at API list prices.

{chr(10).join(chr(10) + s for s in sections)}

## Reproducing a number

`data/release/{v}.json` lists every run file with its hash, the code commit it was made
with and the exact command that reproduces it, plus the environment, the corpus
manifest, the scored query files and the label log with full hashes.
`momentbench diagnose` checks a setup against stored references in about 10 minutes;
`docs/bring-your-system.md` walks from install to a validated, citable result.

## Limitations

Small corpus (27 videos); widely available films the models may already know (record
runs anonymize titles; held-out queries on unseen videos are future work); labels are
model-made and model-adjudicated; the absence screen is coarse; one trial per query;
sampled frames and transcripts, not native video or audio. `docs/scope.md` lists the
rest and the roadmap.
"""
    (ROOT / "docs/report.md").write_text(report)
    print(f"wrote docs/report.md ({len(sections)} domain sections)")


if __name__ == "__main__":
    main()
